    images=set(); receivers0=set(); receivers2=set(); n1=set(); n3=set()
    for lam,mu in product(range(5),repeat=2):
        x=prepare(lam,mu); images.add(x); x0=x
        check(base_chart(x),(2,1,0,lam,mu,0),f"prepared coordinates {lam} {mu}")
        check(chart(x),(2,0,1,0,lam,mu),f"independent chart source {lam} {mu}")
        expected=((2,0),(0,lam),(2,0),(1,mu))
        words=[]
        for n in range(4):
            check(receiver(x),expected[n],f"prefix receiver {lam} {mu} {n}")
            label=BLANK if n in (0,2) else ('PRESENT',lam if n==1 else mu)
            check(read_record(receiver(x)),label,f"prefix read {lam} {mu} {n}")
            if n==0: receivers0.add(receiver(x))
            if n==1:
                n1.add(receiver(x)); check(base_chart(x),(0,3,2,lam,(mu+2)%5,1),'first-step affine chart')
            if n==2:
                receivers2.add(receiver(x)); check(x,x0,'entire-checkpoint restoration')
            if n==3:
                n3.add(receiver(x)); check(base_chart(x),(1,4,0,(-lam)%5,(-mu)%5,2),'third-step affine chart')
                check(invariant_pair(x),(lam,mu),'both messages survive')
            if n<3:
                words.append((sum(x)+2*theta(n))%5); x=step(n,x)
        check(tuple(words),(2,2,4),f"actual selectors {lam} {mu}")
    check(len(images),25,'injective preparation')
    check(receivers0,{(2,0)},'common initial receiver')
    check(receivers2,{(2,0)},'common restored receiver')
    check(n1,{(0,x) for x in range(5)},'first all symbols')
    check(n3,{(1,x) for x in range(5)},'second all symbols')
    return {'preparations':25,'prefix_updates':75,'full_checkpoint_restorations':25,'selectors':[2,2,4],'trace':[2,0,2,1]}

