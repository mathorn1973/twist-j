    for lam,mu in product(range(5),repeat=2):
        carrier=tail(lam,mu)
        check(len(carrier),20,'tail cardinality')
        check(union.isdisjoint(carrier),True,'disjoint message-pair tails')
        union.update(carrier)
        x=prepare(lam,mu)
        for n in range(3): x=step(n,x)
        check(x in carrier,True,'actual tail entrance')
        for x in sorted(carrier):
            check(invariant_pair(x),(lam,mu),'tail labels')
            check(read_record(receiver(x)),('PRESENT',mu),'tail reader')
            for bit in (0,1):
                check(step_bit(x,bit) in carrier,True,f"tail closed {lam} {mu} {x} {bit}")
                edges+=1
    check((len(union),edges),(500,1000),'tail coverage')
    return {'states':len(union),'controlled_edges':edges,'message_pairs':25,'states_per_pair':20,'retention':'induction_not_finite_extrapolation'}

